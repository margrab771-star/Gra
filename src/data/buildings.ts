function computeDefaultSewageWaste(def: BuildingDefinition): { sewage: number; waste: number } {
  if (typeof def.sewageUsage === 'number' && typeof def.wasteUsage === 'number') {
    return { sewage: def.sewageUsage, waste: def.wasteUsage };
  }
  switch (def.category) {
    case 'mining':
      return { sewage: 6, waste: 8 };
    case 'processing':
      return { sewage: 14, waste: 14 };
    case 'energy':
      return def.type === 'coalPowerPlant' ? { sewage: 8, waste: 12 } : { sewage: 2, waste: 2 };
    case 'real_estate':
    case 'attractions':
      return { sewage: 12, waste: 10 };
    case 'safety':
      return def.type === 'hospital' ? { sewage: 16, waste: 14 } : { sewage: 4, waste: 4 };
    case 'waste':
      return { sewage: def.sewageUsage ?? 2, waste: def.wasteUsage ?? 2 };
    default:
      return { sewage: 4, waste: 4 };
  }
}

export const BUILDING_DEFINITIONS: Record<BuildingType, BuildingDefinition> = Object.fromEntries(
  (Object.entries(RAW_BUILDING_DEFINITIONS) as [BuildingType, BuildingDefinition][]).map(([key, def]) => {
    const cleanedReqs = def.requirements
      ? { ...def.requirements, requiredResources: undefined }
      : undefined;
    if (cleanedReqs && Object.values(cleanedReqs).every((v) => v === undefined)) {
      // keep undefined if empty
    }
    const { sewage, waste } = computeDefaultSewageWaste(def);
    const supplemental = SUPPLEMENTAL_BUILDING_NODES[key] ?? [];
    const posOverrides = NODE_GRAPH_POS_OVERRIDES[key];
    const baseAndSupp = [
      ...def.internalTechTree,
      ...supplemental.filter((sn) => !def.internalTechTree.some((dn) => dn.id === sn.id)),
    ];
    const extraApex = APEX_EXTRA_NODES[key];
    const hasApexAlready = baseAndSupp.some((n) => n.isApex || n.effects.isApex);
    const rawTreeUnpositioned =
      !hasApexAlready && extraApex ? [...baseAndSupp, extraApex] : baseAndSupp;
    const rawTree = posOverrides
      ? rawTreeUnpositioned.map((node) =>
          posOverrides[node.id] ? { ...node, graphPos: posOverrides[node.id] } : node
        )
      : rawTreeUnpositioned;

    // Dla struktur Poziomu 1–2 zamień zablokowane na start zasoby high-tech (elektronika/półprzewodniki/chemikalia/broń) na stal/miedź/prefabrykaty
    const nextTree = rawTree.map((node) => {
      if (def.requiredCorpLevel > 2 || !node.requirements?.requiredResources) return node;
      const mappedRes: Partial<Record<import('../engine/types').ResourceType, number>> = {};
      for (const [rKey, qty] of Object.entries(node.requirements.requiredResources)) {
        if (!qty) continue;
        if (rKey === 'electronics') {
          mappedRes.copper = (mappedRes.copper ?? 0) + qty;
        } else if (rKey === 'semiconductors' || rKey === 'weapons') {
          mappedRes.steel = (mappedRes.steel ?? 0) + qty * 2;
        } else if (rKey === 'chemicals') {
          mappedRes.prefabs = (mappedRes.prefabs ?? 0) + qty;
        } else {
          const rk = rKey as import('../engine/types').ResourceType;
          mappedRes[rk] = (mappedRes[rk] ?? 0) + qty;
        }
      }
      return {
        ...node,
        requirements: {
          ...node.requirements,
          requiredResources: mappedRes,
        },
      };
    });

    return [
      key,
      {
        ...def,
        buildConstructionInputs: {},
        requirements: cleanedReqs,
        sewageUsage: def.sewageUsage ?? sewage,
        wasteUsage: def.wasteUsage ?? waste,
        internalTechTree: nextTree,
      },
    ];
  })
) as Record<BuildingType, BuildingDefinition>;

export const BUILDING_DEFINITION_LIST: BuildingDefinition[] = Object.values(BUILDING_DEFINITIONS);
