import type { BuildingDefinition, BuildingTechNode, BuildingType, NonFinancialRequirements } from '../engine/types';

type TechSeed = Omit<BuildingTechNode, 'progress' | 'status'>;

function makeFiveNodeTree(
  prefix: string,
  baseCost: number,
  nodes: {
    n1: { name: string; desc: string; trade: string; eff: BuildingTechNode['effects'] };
    n2: { name: string; desc: string; trade: string; eff: BuildingTechNode['effects'] };
    n3: { name: string; desc: string; trade: string; eff: BuildingTechNode['effects'] };
    n4: { name: string; desc: string; trade: string; eff: BuildingTechNode['effects'] };
    flagship: { name: string; desc: string; trade: string; eff: BuildingTechNode['effects']; reqs?: NonFinancialRequirements };
  }
): TechSeed[] {
  return [
    {
      id: `${prefix}_t1`,
      name: nodes.n1.name,
      description: nodes.n1.desc,
      tradeoffNote: nodes.n1.trade,
      cost: Math.round(baseCost * 0.34),
      researchTicks: 8,
      prerequisites: [],
      category: 'efficiency',
      tier: 1,
      graphPos: { x: 40, y: 45 },
      effects: nodes.n1.eff,
    },
    {
      id: `${prefix}_t2`,
      name: nodes.n2.name,
      description: nodes.n2.desc,
      tradeoffNote: nodes.n2.trade,
      cost: Math.round(baseCost * 0.42),
      researchTicks: 10,
      prerequisites: [],
      category: 'capacity',
      tier: 1,
      graphPos: { x: 40, y: 155 },
      effects: nodes.n2.eff,
    },
    {
      id: `${prefix}_t3`,
      name: nodes.n3.name,
      description: nodes.n3.desc,
      tradeoffNote: nodes.n3.trade,
      cost: Math.round(baseCost * 0.65),
      researchTicks: 13,
      prerequisites: [`${prefix}_t1`],
      category: 'green',
      tier: 2,
      graphPos: { x: 255, y: 45 },
      requirements: { minWorkerSkill: 55 },
      effects: nodes.n3.eff,
    },
    {
      id: `${prefix}_t4`,
      name: nodes.n4.name,
      description: nodes.n4.desc,
      tradeoffNote: nodes.n4.trade,
      cost: Math.round(baseCost * 0.95),
      researchTicks: 16,
      prerequisites: [`${prefix}_t2`],
      category: 'monopoly',
      tier: 3,
      graphPos: { x: 255, y: 155 },
      requirements: { minWorkerSkill: 65, requiredBuildings: ['highSchool'] },
      effects: nodes.n4.eff,
    },
    {
      id: `${prefix}_flagship`,
      name: `${nodes.flagship.name} (Projekt Flagowy)`,
      description: nodes.flagship.desc,
      tradeoffNote: nodes.flagship.trade,
      cost: Math.round(baseCost * 1.45),
      researchTicks: 22,
      prerequisites: [`${prefix}_t3`, `${prefix}_t4`],
      category: 'flagship',
      tier: 4,
      isFlagship: true,
      graphPos: { x: 470, y: 100 },
      requirements: nodes.flagship.reqs ?? { requiredCorpLevel: 3, minWorkerSkill: 72, requiredBuildings: ['university'] },
      effects: { ...nodes.flagship.eff, isApex: true },
    },
  ];
}

