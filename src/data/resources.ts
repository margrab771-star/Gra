export const RESOURCE_LIST: ResourceType[] = Object.keys(RESOURCE_DEFINITIONS) as ResourceType[];
export const TRADEABLE_RESOURCE_LIST: ResourceType[] = RESOURCE_LIST.filter(
  (r) => RESOURCE_DEFINITIONS[r].tradeable !== false
);

export function createInitialResourcePrices(): ResourcePrice[] {
  return TRADEABLE_RESOURCE_LIST.map((type) => {
    const def = RESOURCE_DEFINITIONS[type];
    const history: number[] = [];
    const candles: PriceCandle[] = [];
    let prev = def.basePrice;
    for (let i = 0; i < 20; i++) {
      const wave = Math.sin(i * 0.45 + def.basePrice * 0.01) * def.volatility * 0.6;
      const open = Math.round(prev);
      const close = Math.max(def.minPrice, Math.round(prev * (1 + wave)));
      const high = Math.round(Math.max(open, close) * (1 + def.volatility * 0.35));
      const low = Math.round(Math.min(open, close) * (1 - def.volatility * 0.35));
      history.push(close);
      candles.push({ tick: i - 20, open, high, low, close });
      prev = close;
    }
    const current = history[history.length - 1];
    const previous = history[history.length - 2];
    const changePercent = ((current - previous) / previous) * 100;

    return {
      type,
      name: def.name,
      emoji: def.emoji,
      unit: def.unit,
      price: current,
      previousPrice: previous,
      basePrice: def.basePrice,
      changePercent: Number(changePercent.toFixed(2)),
      supply: 100,
      demand: 100,
      history,
      candles,
    };
  });
}
